export type Lang = 'de' | 'en'

export function detectLang(env: NodeJS.ProcessEnv = process.env): Lang {
  // German for German locales, English for everyone else (ACCORD_LANG wins).
  const value = env.ACCORD_LANG ?? env.LC_ALL ?? env.LANG ?? ''
  return value.toLowerCase().startsWith('de') ? 'de' : 'en'
}

export function translator(lang: Lang) {
  const catalogue: Record<MessageKey, string> = lang === 'en' ? en : de
  return (key: MessageKey, params: Record<string, string | number> = {}) =>
    catalogue[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export type T = ReturnType<typeof translator>
