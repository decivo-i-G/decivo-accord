import { createHash } from 'node:crypto'
import { cssVariableName } from '@decivo/accord-adapter-code'
import {
  type ColorValue,
  type Config,
  colorToCss,
  type DimensionValue,
  dimensionToCss,
  otherContexts,
  type Register,
  type RegisterModes,
  registerInContext,
  type Token,
  tokensDifferingIn,
} from '@decivo/accord-core'

type Obj = Record<string, unknown>
const isObject = (v: unknown): v is Obj => typeof v === 'object' && v !== null && !Array.isArray(v)

const fontFamilyCss = (v: unknown) =>
  (Array.isArray(v) ? v : [v]).map((f) => (/[\s,]/.test(String(f)) ? `"${String(f)}"` : String(f))).join(', ')

function shadowLayerCss(layer: Obj): string {
  const d = (k: string) => dimensionToCss(layer[k] as DimensionValue)
  return [
    layer.inset ? 'inset' : '',
    d('offsetX'),
    d('offsetY'),
    d('blur'),
    d('spread'),
    colorToCss(layer.color as ColorValue),
  ]
    .filter(Boolean)
    .join(' ')
}

/** CSS for a resolved token value, or undefined for types a single property cannot carry (typography). */
export function valueToCss(token: Pick<Token, 'type' | 'value' | 'accord'>): string | undefined {
  if (typeof token.accord?.css === 'string') return token.accord.css
  const v = token.value
  switch (token.type) {
    case 'color':
      return colorToCss(v as ColorValue)
    case 'dimension':
      return dimensionToCss(v as DimensionValue)
    case 'duration':
      return isObject(v) ? `${v.value}${v.unit}` : undefined
    case 'fontFamily':
      return fontFamilyCss(v)
    case 'fontWeight':
    case 'number':
      return String(v)
    case 'cubicBezier':
      return Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : undefined
    case 'shadow':
      return (Array.isArray(v) ? v : [v]).map((l) => shadowLayerCss(l as Obj)).join(', ')
    default:
      return undefined
  }
}

/** `var(--…)` of the aliased token when the token is a reference, else its literal CSS value. */
export function tokenCss(register: Pick<Register, 'tokens'>, token: Token): string | undefined {
  const target = token.aliasOf ? register.tokens.get(token.aliasOf) : undefined
  if (target && typeof token.accord?.css !== 'string') return `var(${cssVariableName(target)})`
  return valueToCss(token)
}

/** Tokens in register order without the copies made by `$extends`. */
export const ownTokens = (register: Pick<Register, 'tokens'>) =>
  [...register.tokens.values()].filter((t) => t.inheritedFrom === undefined)

/**
 * Short fingerprint of the register files. Generated files carry it, so `accord export --check`
 * can tell whether they are up to date without timestamps (which would change on every run).
 */
export function fingerprint(files: readonly { path: string; content: string }[]): string {
  const hash = createHash('sha256')
  for (const f of [...files].sort((a, b) => a.path.localeCompare(b.path))) {
    if (f.path.startsWith('generated/') || f.path.startsWith('proposals/') || f.path === 'surfaces.lock.json')
      continue
    hash.update(f.path).update('\0').update(f.content).update('\0')
  }
  return hash.digest('hex').slice(0, 12)
}

export const GENERATED_NOTICE =
  'Generated by decivo Accord from .accord/ – do not edit by hand; change the register instead.'

/** A register as the generators read it: tokens, and optionally its contexts and config. */
export type GeneratorRegister = Pick<Register, 'tokens'> & {
  modes?: RegisterModes | undefined
  config?: Pick<Config, 'surfaces'> | undefined
}

/** Where a context's values apply in CSS: `surfaces.code.modes`, else `.dark` for dark (F14), `.<context>` otherwise. */
export const contextSelector = (register: GeneratorRegister, context: string): string =>
  register.config?.surfaces.code.modes?.[context] ?? `.${context}`

export interface ContextOutput {
  context: string
  selector: string
  /** The register resolved in this context (aliases point to that context's targets). */
  register: GeneratorRegister
  /** Tokens with an own value in this context, resolved there, in register order (no `$extends` copies). */
  tokens: Token[]
  /** The same by path, for lookups. */
  byPath: Map<string, Token>
}

/** Every non-default context with the tokens that differ there. Empty for a register without modes. */
export function contextOutputs(register: GeneratorRegister): ContextOutput[] {
  return otherContexts(register).map((context) => {
    const tokens = tokensDifferingIn(register, context).filter((t) => t.inheritedFrom === undefined)
    return {
      context,
      selector: contextSelector(register, context),
      register: registerInContext(register, context),
      tokens,
      byPath: new Map(tokens.map((t) => [t.path, t])),
    }
  })
}
