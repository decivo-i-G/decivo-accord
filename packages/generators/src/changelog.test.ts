import { describe, expect, it } from 'vitest'
import { generateChangelog } from './changelog.js'
import { fingerprint } from './values.js'

const proposal = (id: string, resolution?: object, extra: object = {}) => ({
  path: `proposals/${id}.json`,
  content: JSON.stringify({
    id,
    source: 'claude-design',
    bundle: { name: id.slice(11) },
    ...extra,
    resolution,
  }),
})

describe('CHANGELOG.md', () => {
  it('is empty while nothing has been decided', () => {
    expect(generateChangelog([proposal('P-20261018-open')])).toBeUndefined()
  })

  it('lists decisions newest first, grouped by day, with person, reference, tokens and note', () => {
    const md = generateChangelog([
      proposal('P-20261017-alt', { option: 'reject', by: 'Tobias', at: '2026-10-17T09:00:00Z' }),
      proposal('P-20261018-landing', {
        option: 'adopt',
        items: [
          { token: 'color.brand.$root', value: '#4A7B9A', kind: 'change' },
          { token: 'color.brand.600', value: '#4a7d9b', kind: 'new' },
          { token: 'font.family.sans', value: 'Inter', kind: 'change' },
          { token: 'color.legacy', kind: 'remove' },
        ],
        by: 'Janni',
        at: '2026-10-18T14:00:00Z',
        ref: 'review:123',
        note: 'Rebrush',
      }),
      proposal('P-20261018-open'),
      { path: 'proposals/kaputt.json', content: '{' },
    ])
    expect(md).toBe(
      [
        '# Design system changelog',
        '',
        '> Generated by decivo Accord from .accord/ – do not edit by hand; change the register instead.',
        '',
        '## 2026-10-18',
        '',
        '- **Adopted** `P-20261018-landing` "landing" (claude-design), decided by Janni (review:123)',
        '  - `color.brand.$root`: #4a7b9a',
        '  - `color.brand.600`: new token #4a7d9b',
        '  - `font.family.sans`: Inter',
        '  - `color.legacy`: removed',
        '  - Rebrush',
        '',
        '## 2026-10-17',
        '',
        '- **Rejected** `P-20261017-alt` "alt" (claude-design), decided by Tobias',
        '',
      ].join('\n'),
    )
  })

  it('a decision does not change the fingerprint of the generated files', () => {
    const base = [{ path: 'accord.config.yaml', content: 'version: 1\n' }]
    const decidedOne = proposal('P-20261018-x', { option: 'reset', by: 'Janni', at: '2026-10-18T14:00:00Z' })
    expect(fingerprint([...base, decidedOne])).toBe(fingerprint(base))
  })
})
