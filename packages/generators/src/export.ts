import type { Register, RegisterFile } from '@decivo/accord-core'
import { generateAgentsMd, generateClaudeMdBlock, upsertManagedBlock } from './agents-md.js'
import { generateChangelog } from './changelog.js'
import { generateCss, generateTailwindTheme } from './css.js'
import { DESIGN_MD_MARKER, generateDesignMd } from './design-md.js'
import { fingerprint } from './values.js'

export type OutputMode =
  /** Whole file is Accord's. */
  | 'generated'
  /** Accord owns a marked block inside a hand-written file. */
  | 'block'
  /** A hand-written file exists where Accord would write; left untouched. */
  | 'skipped'

export interface PlannedOutput {
  /** Path relative to the repository root. */
  path: string
  mode: OutputMode
  content: string
  /** Current content on disk, if any. */
  existing?: string | undefined
  changed: boolean
}

export interface ExportInput {
  register: Register
  /** Register files, for the fingerprint. */
  files: readonly RegisterFile[]
  /** Register directory relative to the repository root, e.g. `.accord`. */
  registerDir: string
  /** Reads a repository-relative file; undefined when it does not exist. */
  read: (path: string) => Promise<string | undefined>
}

/**
 * Everything `accord export` writes, without writing it. DESIGN.md, AGENTS.md and, once proposals have
 * been decided, CHANGELOG.md always go to `<register>/generated/`; the configured root files are written as a whole (DESIGN.md, only if
 * it is missing or was generated by Accord) or as a marked block (AGENTS.md, CLAUDE.md).
 */
export async function planExport({
  register,
  files,
  registerDir,
  read,
}: ExportInput): Promise<PlannedOutput[]> {
  const fp = fingerprint(files)
  const { config } = register
  const designMd = generateDesignMd(register, { name: config.name, fingerprint: fp })
  const agentsMd = generateAgentsMd(register, { fingerprint: fp })
  const plans: PlannedOutput[] = []

  const add = async (path: string, mode: OutputMode, make: (existing: string | undefined) => string) => {
    const existing = await read(path)
    const content = make(existing)
    plans.push({ path, mode, content, existing, changed: mode !== 'skipped' && content !== existing })
  }

  await add(`${registerDir}/generated/DESIGN.md`, 'generated', () => designMd)
  await add(`${registerDir}/generated/AGENTS.md`, 'generated', () => agentsMd)
  const changelog = generateChangelog(files)
  if (changelog) await add(`${registerDir}/generated/CHANGELOG.md`, 'generated', () => changelog)

  const designPath = config.outputs.design_md
  const existingDesign = await read(designPath)
  if (designPath === `${registerDir}/generated/DESIGN.md`) {
    // Configured to live in generated/ only; already planned above.
  } else if (existingDesign === undefined || existingDesign.includes(DESIGN_MD_MARKER))
    await add(designPath, 'generated', () => designMd)
  else
    plans.push({
      path: designPath,
      mode: 'skipped',
      content: designMd,
      existing: existingDesign,
      changed: false,
    })

  await add(config.outputs.agents_md, 'block', (existing) => upsertManagedBlock(existing, agentsMd))
  if (config.outputs.claude_md) {
    const block = generateClaudeMdBlock({ fingerprint: fp, agentsPath: config.outputs.agents_md, register })
    await add(config.outputs.claude_md, 'block', (existing) => upsertManagedBlock(existing, block))
  }

  for (const output of config.surfaces.code.outputs) {
    const content = output.format === 'css' ? generateCss(register, fp) : generateTailwindTheme(register, fp)
    await add(output.path, 'generated', () => content)
  }
  return plans
}
